function renderLaws(items, target, filter = "") {
  const root = document.getElementById(target);
  const q = filter.trim().toLowerCase();
  const shown = items.filter(([n, title, text]) =>
    `${title} ${text}`.toLowerCase().includes(q)
  );
  root.innerHTML = shown.map(([number, title, text]) => `
    <article class="law">
      <div class="law-top">
        <span class="law-number">LAW ${number}</span>
      </div>
      <h3>${title}</h3>
      <p>${text}</p>
    </article>
  `).join("");
  return shown.length;
}

